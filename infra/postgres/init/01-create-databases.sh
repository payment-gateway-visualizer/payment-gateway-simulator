#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<EOSQL

CREATE USER auth_user WITH PASSWORD '${AUTH_DB_PASSWORD}';
CREATE USER wallet_user WITH PASSWORD '${WALLET_DB_PASSWORD}';
CREATE USER settlement_user WITH PASSWORD '${SETTLEMENT_DB_PASSWORD}';

CREATE DATABASE auth_db OWNER auth_user;
CREATE DATABASE wallet_db OWNER wallet_user;
CREATE DATABASE settlement_db OWNER settlement_user;

REVOKE CONNECT ON DATABASE auth_db FROM PUBLIC;
REVOKE CONNECT ON DATABASE wallet_db FROM PUBLIC;
REVOKE CONNECT ON DATABASE settlement_db FROM PUBLIC;

EOSQL